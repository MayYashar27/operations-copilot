"""FastAPI app for Operations Copilot.

Run locally (from the project root):
    uvicorn api.main:app --reload
Then open http://127.0.0.1:8000/docs

Report endpoints here are READ-ONLY and never call Claude: AI results are
pre-generated by scripts/generate_report.py and read from disk. The only
endpoints that can start paid AI work live in copilot_routes.py, behind the
live-mode + local-machine checks.
"""

import datetime as dt
import logging
from typing import List, Optional

from fastapi import FastAPI, Path, Request
from fastapi.responses import JSONResponse

from api import service, storage
from api.config import DISCLAIMER, Settings, load_settings
from api.copilot_routes import build_router
from api.copilot_runner import InvestigationRunner
from api.copilot_store import InvestigationStore, JsonInvestigationStore
from api.schemas import AgentDetail, AgentRow, AppConfig, ReportListItem, ReportOverview


logger = logging.getLogger("operations_copilot.api")

AGENT_ID_PATTERN = r"^[A-Za-z0-9_-]{1,32}$"


def create_app(
    settings: Optional[Settings] = None,
    store: Optional[InvestigationStore] = None,
    runner: Optional[InvestigationRunner] = None,
) -> FastAPI:
    """Build the app. Tests pass their own Settings, store and runner."""

    settings = settings or load_settings()
    if store is None:
        json_store = JsonInvestigationStore(
            examples_dir=settings.investigations_dir / "examples",
            local_dir=settings.investigations_dir / "local",
        )
        json_store.mark_interrupted()  # runs cut off by a restart are marked failed
        store = json_store
    runner = runner or InvestigationRunner(store, settings.reports_dir)
    app = FastAPI(
        title="Operations Copilot API",
        description="Read-only access to saved screening reports and investigations.",
        version="0.1.0",
    )

    # ---------------------------------------------------------
    # Error handling: map internal errors to clear HTTP responses.
    # Messages never include file paths or stack traces.
    # ---------------------------------------------------------

    def error(status: int, message: str) -> JSONResponse:
        return JSONResponse(status_code=status, content={"detail": message})

    @app.exception_handler(storage.ReportNotFoundError)
    async def report_not_found(_: Request, exc: Exception) -> JSONResponse:
        return error(404, str(exc))

    @app.exception_handler(service.AgentNotFoundError)
    async def agent_not_found(_: Request, exc: Exception) -> JSONResponse:
        return error(404, str(exc))

    @app.exception_handler(storage.ReportMalformedError)
    async def report_malformed(_: Request, exc: Exception) -> JSONResponse:
        logger.exception("Malformed saved data")
        return error(500, str(exc))

    @app.exception_handler(service.DataUnavailableError)
    async def data_unavailable(_: Request, exc: Exception) -> JSONResponse:
        logger.exception("Source data unavailable")
        return error(503, str(exc))

    # ---------------------------------------------------------
    # Read-only endpoints
    # ---------------------------------------------------------

    @app.get("/api/health")
    def health() -> dict:
        return {"status": "ok"}

    @app.get("/api/config", response_model=AppConfig)
    def config() -> AppConfig:
        """What the UI needs to know about this server (never secrets)."""
        return AppConfig(
            mode=settings.app_mode,
            live_investigations_enabled=settings.live_investigations_enabled,
            disclaimer=DISCLAIMER,
        )

    @app.get("/api/reports", response_model=List[ReportListItem])
    def list_reports() -> List[ReportListItem]:
        """Dates that have a saved daily report, newest first."""
        return service.list_reports(settings)

    @app.get("/api/reports/{date}", response_model=ReportOverview)
    def report_overview(date: dt.date) -> ReportOverview:
        """Dashboard data: status counts, day metrics, priority items."""
        return service.get_overview(settings, date.isoformat())

    @app.get("/api/reports/{date}/agents", response_model=List[AgentRow])
    def report_agents(date: dt.date) -> List[AgentRow]:
        """One row per screened agent, with that day's metrics."""
        return service.list_agents(settings, date.isoformat())

    @app.get("/api/reports/{date}/agents/{agent_id}", response_model=AgentDetail)
    def agent_detail(
        date: dt.date,
        agent_id: str = Path(pattern=AGENT_ID_PATTERN),
    ) -> AgentDetail:
        """Full detail for one agent: metrics, trends, signals, investigation."""
        return service.get_agent_detail(settings, date.isoformat(), agent_id)

    app.include_router(build_router(settings, store, runner))
    return app


app = create_app()
