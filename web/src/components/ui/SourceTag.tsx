import { Activity, Sparkles } from 'lucide-react'

export type EvidenceSource = 'rule' | 'ai'

const SOURCE_META = {
  rule: {
    label: 'Metric signal',
    title: 'Produced by deterministic threshold rules on the request data. No AI involved.',
    Icon: Activity,
    tag: 'bg-rule-bg text-rule-ink',
    icon: 'text-rule',
  },
  ai: {
    label: 'AI observation',
    title: 'Generated by Claude from the request documentation. Requires human validation.',
    Icon: Sparkles,
    tag: 'bg-ai-bg text-ai-ink',
    icon: 'text-ai',
  },
} as const

/** Labels where a piece of evidence came from: a rule or the AI. */
export function SourceTag({ source, label }: { source: EvidenceSource; label?: string }) {
  const meta = SOURCE_META[source]
  return (
    <span title={meta.title}
      className={`inline-flex items-center gap-1 rounded-full px-2 py-[2px] text-[11px] font-semibold whitespace-nowrap ${meta.tag}`}>
      <meta.Icon aria-hidden className="size-3" strokeWidth={2.25} />
      {label ?? meta.label}
    </span>
  )
}

export function SourceIcon({ source, className = 'size-3.5' }: { source: EvidenceSource; className?: string }) {
  const meta = SOURCE_META[source]
  return <meta.Icon aria-label={meta.label} className={`${className} ${meta.icon}`} strokeWidth={2.1} />
}
